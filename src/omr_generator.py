
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.pdfgen import canvas


# ==========================================
# 1. PROJECT CONFIGURATION
# ==========================================

PROJECT_DIR = Path(__file__).resolve().parent.parent

TEMPLATE_DIR = PROJECT_DIR / "templates"

OUTPUT_FILE = TEMPLATE_DIR / "standard_100_question_omr.pdf"

PAGE_WIDTH, PAGE_HEIGHT = A4

TOTAL_QUESTIONS = 100
OPTIONS = ["A", "B", "C", "D"]


# ==========================================
# 2. DRAW REGISTRATION MARKERS
# ==========================================

def draw_registration_markers(pdf):
    """Draw four black square markers for sheet alignment."""

    marker_size = 14
    margin = 22

    positions = [
        (margin, margin),
        (PAGE_WIDTH - margin - marker_size, margin),
        (margin, PAGE_HEIGHT - margin - marker_size),
        (
            PAGE_WIDTH - margin - marker_size,
            PAGE_HEIGHT - margin - marker_size
        )
    ]

    pdf.setFillColor(colors.black)

    for x, y in positions:
        pdf.rect(
            x,
            y,
            marker_size,
            marker_size,
            fill=1,
            stroke=0
        )


# ==========================================
# 3. DRAW STUDENT INFORMATION
# ==========================================

def draw_student_information(pdf):

    pdf.setFont("Helvetica-Bold", 18)

    pdf.drawCentredString(
        PAGE_WIDTH / 2,
        785,
        "SMARTOMR AI - ANSWER SHEET"
    )

    pdf.setFont("Helvetica", 10)

    pdf.drawString(48, 748, "Student Name:")

    pdf.line(125, 746, 320, 746)

    pdf.drawString(345, 748, "Roll No:")

    pdf.line(395, 746, 540, 746)

    pdf.drawString(48, 720, "Exam Name:")

    pdf.line(112, 718, 320, 718)

    pdf.drawString(345, 720, "Exam ID:")

    pdf.line(395, 718, 540, 718)

    pdf.setFont("Helvetica-Bold", 9)

    pdf.drawString(
        48,
        688,
        "Instructions: Fill only one bubble per question using a dark pen."
    )


# ==========================================
# 4. DRAW ANSWER BUBBLES
# ==========================================

def draw_answer_column(pdf, start_question, end_question, x_position):

    row_start_y = 645
    row_gap = 10.2

    bubble_radius = 4.5

    # Horizontal positions of A, B, C and D bubbles
    bubble_positions = [
        x_position + 90,
        x_position + 124,
        x_position + 158,
        x_position + 192
    ]

    # Draw option labels
    pdf.setFont("Helvetica-Bold", 8)

    for option, x in zip(OPTIONS, bubble_positions):
        pdf.drawCentredString(x, 660, option)

    # Draw questions and bubbles
    for question_number in range(start_question, end_question + 1):

        row_index = question_number - start_question

        y_position = row_start_y - (row_index * row_gap)

        pdf.setFont("Helvetica", 8)

        pdf.drawString(
            x_position + 10,
            y_position - 3,
            f"{question_number}."
        )

        for x in bubble_positions:

            pdf.setStrokeColor(colors.black)

            pdf.circle(
                x,
                y_position,
                bubble_radius,
                fill=0,
                stroke=1
            )


# ==========================================
# 5. GENERATE OMR PDF
# ==========================================

def generate_omr_sheet():

    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)

    pdf = canvas.Canvas(
        str(OUTPUT_FILE),
        pagesize=A4
    )

    pdf.setTitle("SmartOMR AI - 100 Question Answer Sheet")

    # Draw sheet elements
    draw_registration_markers(pdf)

    draw_student_information(pdf)

    # Two columns: 50 questions each
    draw_answer_column(
        pdf,
        start_question=1,
        end_question=50,
        x_position=48
    )

    draw_answer_column(
        pdf,
        start_question=51,
        end_question=100,
        x_position=310
    )

    # Footer
    pdf.setFont("Helvetica", 8)

    pdf.drawCentredString(
        PAGE_WIDTH / 2,
        45,
        "Generated by SmartOMR AI"
    )

    pdf.save()

    print("OMR sheet generated successfully!")
    print(f"Saved at: {OUTPUT_FILE}")


# ==========================================
# 6. RUN GENERATOR
# ==========================================

if __name__ == "__main__":
    generate_omr_sheet()
